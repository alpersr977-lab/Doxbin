def kali_prompt():
    """Kali Linux tarzı prompt"""
    user = "root"
    host = "doxbin"
    path = "~"
    prompt = f"{C.RED}┌──({C.BOLD}{user}㉿{host}{C.RESET}{C.RED})-[{C.WHITE}{path}{C.RED}]\n"
    prompt += f"{C.RED}└─{C.RESET}{C.RED}# {C.RESET}"
    return prompt

def spinner(duration=1.5, text="Scanning"):
    chars = ['|', '/', '-', '\\']
    end_time = time.time() + duration
    i = 0
    while time.time() < end_time:
        sys.stdout.write(f"\r  {C.RED}[*]{C.RESET} {C.WHITE}{text}... {C.RED}{chars[i % 4]}{C.RESET}")
        sys.stdout.flush()
        time.sleep(0.1)
        i += 1
    sys.stdout.write("\r" + " " * 60 + "\r")

